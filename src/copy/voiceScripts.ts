/** Bộ quản lý lịch sử ngẫu nhiên không lặp lại (Non-repeating pool) */
export class NonRepeatingVoicePicker {
  private history: Map<string, string[]> = new Map();
  private maxHistory: number;

  constructor(maxHistory = 20) {
    this.maxHistory = maxHistory;
  }

  public pick(key: string, pool: readonly string[]): string {
    if (!pool || pool.length === 0) return '';
    if (pool.length === 1) return pool[0];

    const used = this.history.get(key) || [];
    const available = pool.filter((item) => !used.includes(item));
    const candidates = available.length > 0 ? available : pool;

    const chosen = candidates[Math.floor(Math.random() * candidates.length)];
    const newHistory = [...used, chosen];
    if (newHistory.length > Math.min(this.maxHistory, pool.length - 1)) {
      newHistory.shift();
    }
    this.history.set(key, newHistory);
    return chosen;
  }

  public reset(key?: string) {
    if (key) {
      this.history.delete(key);
    } else {
      this.history.clear();
    }
  }
}

export const defaultVoicePicker = new NonRepeatingVoicePicker(25);

